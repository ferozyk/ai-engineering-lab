"""The vocabulary of the generated corpus: twenty fictional Lab Bank products.

Everything the generator writes comes from this table and from the templates in ``render.py``.
Nothing here is random. A field is ``Field(name, kind, description)``; ``kind`` is one of
``str``, ``date``, ``dt``, ``int``, ``num``, ``ccy``, ``uri``, ``money:<max>`` or
``enum:a|b|c``.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Field:
    """One property of a product's main resource."""

    name: str
    kind: str
    description: str


@dataclass(frozen=True)
class Action:
    """The product-specific operation, for example ``freezeCard``."""

    operation_id: str
    segment: str  # last path segment, for example "freeze"
    summary: str
    description: str
    body: tuple[Field, ...]


@dataclass(frozen=True)
class Product:
    """One product family; each is published as separate v1, v2 (and sometimes v3) specs."""

    key: str  # stable id and scope prefix, for example "cards"
    prefix: str  # error-code prefix, for example "CRD"
    title: str  # for example "Cards"
    segment: str  # path segment, for example "cards"
    resource: str  # singular noun, for example "card"
    plural: str
    id_param: str  # path parameter, for example "cardId"
    type_name: str  # schema name of the resource, for example "Card"
    blurb: str  # first sentence of info.description
    fields: tuple[Field, ...]  # after the automatic ``id`` field; the first ``enum`` is the status
    renames: tuple[tuple[str, str], ...]  # field renames, one per version step
    states: tuple[str, ...]  # 3-5 states for the look-alike conflict (409) codes
    limit_noun: str  # "the {limit_noun} is above the daily limit"
    limit_kinds: tuple[str, ...]  # three kinds of limit for the business-rule (422) codes
    action: Action


F = Field
A = Action

